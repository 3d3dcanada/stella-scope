fn reply(stream: &mut impl Write,code:u16,ctype:&str,body:&[u8]) {
    let reason=match code {200=>"OK",404=>"Not Found",405=>"Method Not Allowed",_=>"Error"};
    let _=write!(stream,"HTTP/1.1 {code} {reason}\r\nContent-Type: {ctype}\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",body.len());
    let _=stream.write_all(body);
}
