// Probe landings for the probing states, as (x, y, z, seconds since start), looping every 40 s.
// meshing: a 5 x 5 mesh over 40..310, one point every 1.2 s. qgl: the four gantry corners, three
// rounds, each round's corrections shrinking.
fn probe_points(state: &str, elapsed: f64) -> Vec<(f64, f64, f64, f64)> {
    let t = elapsed % 40.0;
    let base = elapsed - t;
    let mut out = Vec::new();
    if state == "meshing" {
        for k in 0..25 {
            let at = 1.0 + k as f64 * 1.2;
            if at > t { break; }
            let (c, r) = (k % 5, k / 5);
            let (x, y) = (40.0 + c as f64 * 67.5, 40.0 + r as f64 * 67.5);
            let z = 0.04 * ((x - 175.0) / 175.0) - 0.03 * ((y - 175.0) / 175.0).powi(2) + 0.01 * (k as f64 * 1.7).sin();
            out.push((x, y, z, base + at));
        }
    } else if state == "qgl" {
        let corners = [(27.05, 24.28), (27.05, 319.28), (297.05, 319.28), (297.05, 24.28)];
        for k in 0..12 {
            let at = 1.0 + k as f64 * 1.5;
            if at > t { break; }
            let (x, y) = corners[k % 4];
            let round = (k / 4) as f64;
            out.push((x, y, 0.1 + 0.3 / (1.0 + round * 4.0) * ((k % 4) as f64 - 1.5) / 1.5, base + at));
        }
    }
    out
}
fn gcode_store(state: &str, elapsed: f64, epoch: f64) -> String {
    let mut lines: Vec<(f64, String, &str)> = Vec::new();
    let pts = probe_points(state, elapsed);
    if state == "bltouch_fail" {
        lines.push((2.0, "G28".into(), "command"));
        lines.push((3.0, "!! BLTouch failed to verify sensor state".into(), "response"));
    }
    if let Some(first) = pts.first() {
        let cmd = if state == "qgl" { "QUAD_GANTRY_LEVEL" } else { "BED_MESH_CALIBRATE" };
        lines.push((first.3 - 0.5, cmd.into(), "command"));
    }
    for (i, (x, y, z, at)) in pts.iter().enumerate() {
        lines.push((*at, format!("// probe: at {x:.3},{y:.3} bed will contact at z={z:.6}"), "response"));
        if state == "qgl" && i % 4 == 3 {
            let round = i / 4;
            let r = 0.3 / (1.0 + round as f64 * 4.0);
            lines.push((at + 0.2, format!("// Making the following Z adjustments:\n// stepper_z = {:.6}\n// stepper_z1 = {:.6}\n// stepper_z2 = {:.6}\n// stepper_z3 = {:.6}", -r/2.0, r/3.0, r/2.0, -r/3.0), "response"));
            lines.push((at + 0.3, format!("// Retries: {round}/5 Probed points range: {r:.6} tolerance: 0.020000"), "response"));
        }
    }
    let body: Vec<String> = lines.iter().map(|(t, m, k)| format!(r#"{{"message":{},"time":{:.3},"type":"{k}"}}"#, json_string(m), epoch + t)).collect();
    format!(r#"{{"result":{{"gcode_store":[{}]}}}}"#, body.join(","))
}
fn json_string(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() { match c { '"' => o.push_str("\\\""), '\\' => o.push_str("\\\\"), '\n' => o.push_str("\\n"), c => o.push(c) } }
    o.push('"');
    o
}
