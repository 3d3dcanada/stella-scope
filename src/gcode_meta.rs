    /// A binary file is built the way PrusaSlicer writes it: header, file metadata, printer metadata,
    /// then a compressed G-code block that must never be read.
    fn bgcode() -> Vec<u8> {
        let mut out = b"GCDE".to_vec();
        out.extend_from_slice(&1_u32.to_le_bytes());
        out.extend_from_slice(&1_u16.to_le_bytes());
        let mut block = |kind: u16, comp: u16, data: &[u8], params: &[u8]| {
            out.extend_from_slice(&kind.to_le_bytes());
            out.extend_from_slice(&comp.to_le_bytes());
            out.extend_from_slice(&(data.len() as u32).to_le_bytes());
            if comp != 0 {
                out.extend_from_slice(&(data.len() as u32).to_le_bytes());
            }
            out.extend_from_slice(params);
            out.extend_from_slice(data);
            out.extend_from_slice(&[0, 0, 0, 0]); // CRC32, not checked
        };
        block(
            0,
            0,
            b"Producer=PrusaSlicer 2.9.6\nProduced on=2026-09-21 at 15:17:28 UTC\n",
            &[0, 0],
        );
        block(
            3,
            0,
            b"printer_model=COREONEL\nfilament_type=PETG\nnozzle_diameter=0.4\nmax_layer_z=4.00\nobjects_info={\"objects\":[{\"name\":\"a.stl\",\"polygon\":[[45.5,71.0],[254.5,71.0],[254.5,229.0],[45.5,229.0]]}]}\nfilament used [g]=30.83\n",
            &[0, 0],
        );
        block(1, 3, &[0xAA; 64], &[2, 0]);
        out
    }

