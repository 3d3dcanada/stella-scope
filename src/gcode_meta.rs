//! What a sliced file says about itself (farm board WO-08): which printer it was made for, the nozzle,
//! the filament, the bed it assumed and how big the print is. Nothing here sends anything anywhere.
//!
//! Three real formats were read from our job folders for this (2026-10-12), not guessed:
//! - PrusaSlicer text G-code: `; key = value` lines at the very end (`printer_model = COREONEL`,
//!   `nozzle_diameter`, `filament_type`, `bed_shape = 0x0,300x0,300x300,0x300`, `max_print_height`).
//! - OrcaSlicer text G-code: a `; HEADER_BLOCK_START` block (`max_z_height`, `total layer number`) and the
//!   same kind of `; key = value` lines at the end (`printer_model = Anycubic Kobra X`,
//!   `printable_area = 0x0,260x0,260x260,0x260`, `nozzle_diameter = 0.25`, `filament_type = PETG;PETG`).
//! - PrusaSlicer binary G-code (`GCDE`): blocks, of which the file and printer metadata blocks are plain
//!   `key=value` text (`printer_model=COREONEL`, `nozzle_diameter=0.4`, `objects_info={...polygons...}`).
//!   The G-code itself is compressed and is never read.
//!
//! The size of a text file's print comes from its extruding moves (one streaming pass); a binary file's
//! comes from the object outlines in its printer metadata. A file that says nothing leaves a field
//! unknown, and unknown is never turned into a guess.
use crate::Result;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::{
    fs::File,
    io::{BufRead, BufReader, Read, Seek, SeekFrom},
    path::Path,
};

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Meta {
    /// "PrusaSlicer 2.9.6", "OrcaSlicer 2.4.2".
    pub slicer: Option<String>,
    /// The slicer's printer model: `COREONEL`, `Anycubic Kobra X`, `Adventurer 5M`.
    pub printer_model: Option<String>,
    /// The slicer's printer profile name, when it has one.
    pub printer_profile: Option<String>,
    pub nozzle_mm: Option<f64>,
    /// One entry per filament in the file (`PETG;PETG;PETG` is three).
    pub filament: Vec<String>,
    /// The bed the file was sliced for: width and depth, mm.
    pub bed_mm: Option<[f64; 2]>,
    pub max_height_mm: Option<f64>,
    /// The print itself: size in X, size in Y, highest Z, mm.
    pub extents_mm: Option<[f64; 3]>,
    /// Where the print sits on the bed: min X, min Y, max X, max Y.
    pub bounds_mm: Option<[f64; 4]>,
    pub layers: Option<u32>,
    pub binary: bool,
}

/// Read what the file says. `scan` also walks a text file's moves for the print's size (a few seconds
/// for a 50 MB file); a binary file never needs it.
pub fn read(path: &Path, scan: bool) -> Result<Meta> {
    let mut f = File::open(path).map_err(|e| format!("cannot open {}: {e}", path.display()))?;
    let mut magic = [0_u8; 4];
    let n = f
        .read(&mut magic)
        .map_err(|e| format!("cannot read {}: {e}", path.display()))?;
    if n == 4 && &magic == b"GCDE" {
        return binary(&mut f);
    }
    f.seek(SeekFrom::Start(0)).map_err(|e| e.to_string())?;
    text(&mut f, scan)
}

// ---- text ---------------------------------------------------------------------------------------

fn text(f: &mut File, scan: bool) -> Result<Meta> {
    let len = f.metadata().map_err(|e| e.to_string())?.len();
    let mut m = Meta::default();
    // The head: slicer and the Orca header block.
    let mut head = vec![0_u8; len.min(64 * 1024) as usize];
    f.read_exact(&mut head).map_err(|e| e.to_string())?;
    let head = String::from_utf8_lossy(&head).into_owned();
    for line in head.lines().take(400) {
        let l = line.trim();
        if let Some(rest) = l.strip_prefix("; generated by ") {
            m.slicer = Some(rest.split(" on ").next().unwrap_or(rest).trim().to_owned());
        } else if let Some(v) = l.strip_prefix("; max_z_height:") {
            m.max_height_mm = v.trim().parse().ok();
        } else if let Some(v) = l.strip_prefix("; total layer number:") {
            m.layers = v.trim().parse().ok();
        }
    }
    // The tail: the slicer's whole configuration as `; key = value`.
    let tail_len = len.min(256 * 1024);
    f.seek(SeekFrom::Start(len - tail_len))
        .map_err(|e| e.to_string())?;
    let mut tail = vec![0_u8; tail_len as usize];
    f.read_exact(&mut tail).map_err(|e| e.to_string())?;
    let tail = String::from_utf8_lossy(&tail).into_owned();
    let mut printable_height = None;
    for line in tail.lines() {
        let Some((k, v)) = line
            .trim()
            .strip_prefix("; ")
            .and_then(|l| l.split_once(" = "))
        else {
            continue;
        };
        let v = v.trim();
        match k {
            "printer_model" if !v.is_empty() => m.printer_model = Some(v.to_owned()),
            "printer_settings_id" if !v.is_empty() => m.printer_profile = Some(v.to_owned()),
            "nozzle_diameter" => {
                m.nozzle_mm = v
                    .split([',', ';'])
                    .next()
                    .and_then(|x| x.trim().parse().ok())
            }
            "filament_type" => {
                m.filament = v
                    .split(';')
                    .map(|x| x.trim().to_owned())
                    .filter(|x| !x.is_empty())
                    .collect()
            }
            "bed_shape" | "printable_area" => m.bed_mm = bed_of(v),
            "max_print_height" | "printable_height" => printable_height = v.parse::<f64>().ok(),
            _ => {}
        }
    }
    // The height a printer allows is not the height of this print; keep both apart.
    let _ = printable_height;
    if scan && m.extents_mm.is_none() {
        f.seek(SeekFrom::Start(0)).map_err(|e| e.to_string())?;
        if let Some((b, z)) = moves_extent(BufReader::with_capacity(1 << 20, &*f)) {
            m.bounds_mm = Some(b);
            m.extents_mm = Some([b[2] - b[0], b[3] - b[1], z]);
        }
    }
    Ok(m)
}

/// `0x0,300x0,300x300,0x300` -> [300, 300] (largest x, largest y of the corners).
fn bed_of(v: &str) -> Option<[f64; 2]> {
    let (mut mx, mut my, mut n) = (0.0_f64, 0.0_f64, 0);
    let (mut lx, mut ly) = (f64::MAX, f64::MAX);
    for c in v.split(',') {
        let (x, y) = c.trim().split_once('x')?;
        let (x, y): (f64, f64) = (x.parse().ok()?, y.parse().ok()?);
        mx = mx.max(x);
        my = my.max(y);
        lx = lx.min(x);
        ly = ly.min(y);
        n += 1;
    }
    (n >= 3 && mx - lx > 10.0 && my - ly > 10.0).then_some([mx - lx, my - ly])
}

fn word(s: &str, key: u8) -> Option<f64> {
    // The number that follows `key` in a G-code word list, read by hand: this runs on every line of a
    // file that can be 50 MB.
    let b = s.as_bytes();
    let i = b.iter().position(|&c| c == key)?;
    let rest = &s[i + 1..];
    let end = rest
        .find(|c: char| !(c.is_ascii_digit() || c == '.' || c == '-' || c == '+'))
        .unwrap_or(rest.len());
    rest[..end].parse().ok()
}

/// Walk the moves; the print is where the nozzle extrudes. Handles G90/G91, M82/M83 and `G92 E`.
fn moves_extent<R: BufRead>(mut r: R) -> Option<([f64; 4], f64)> {
    let (mut x, mut y, mut z, mut e) = (0.0_f64, 0.0_f64, 0.0_f64, 0.0_f64);
    let (mut rel_xyz, mut rel_e) = (false, false);
    // Finish-2 F06 (2026-10-19): the start G-code's purge line is extruded plastic that is not part of the print (the CORE One L's runs along the
    // front of the plate), and it made a 125 mm bowl read 158 x 213 mm on the queue's size chip. PrusaSlicer and OrcaSlicer say what a stretch of
    // moves is in `;TYPE:` (Orca also `; FEATURE:`) comments; `Custom` is the slicer's own start, end and change G-code, never the part.
    let mut custom = false;
    let (mut minx, mut miny, mut maxx, mut maxy, mut maxz) =
        (f64::MAX, f64::MAX, f64::MIN, f64::MIN, 0.0_f64);
    let mut any = false;
    let mut buf = String::new();
    loop {
        buf.clear();
        match r.read_line(&mut buf) {
            Ok(0) | Err(_) => break,
            Ok(_) => {}
        }
        if let Some(t) = buf.trim_start().strip_prefix(';') {
            let t = t.trim_start();
            if let Some(kind) = t.strip_prefix("TYPE:").or_else(|| t.strip_prefix("FEATURE:")) {
                custom = kind.trim().eq_ignore_ascii_case("custom");
            }
        }
        let line = buf.split(';').next().unwrap_or("").trim();
        if line.len() < 2 {
            continue;
        }
        let b = line.as_bytes();
        if b[0] == b'G' || b[0] == b'M' {
            let code_end = line.find(char::is_whitespace).unwrap_or(line.len());
            match &line[..code_end] {
                "G90" => rel_xyz = false,
                "G91" => rel_xyz = true,
                "M82" => rel_e = false,
                "M83" => rel_e = true,
                "G92" => {
                    if let Some(v) = word(&line[code_end..], b'E') {
                        e = v;
                    }
                }
                "G0" | "G1" => {
                    let (sx, sy) = (x, y);
                    let args = &line[code_end..];
                    let (nx, ny, nz, ne) = (
                        word(args, b'X'),
                        word(args, b'Y'),
                        word(args, b'Z'),
                        word(args, b'E'),
                    );
                    if rel_xyz {
                        x += nx.unwrap_or(0.0);
                        y += ny.unwrap_or(0.0);
                        z += nz.unwrap_or(0.0);
                    } else {
                        x = nx.unwrap_or(x);
                        y = ny.unwrap_or(y);
                        z = nz.unwrap_or(z);
                    }
                    let extruding = match ne {
                        Some(v) if rel_e => v > 0.0,
                        Some(v) => {
                            let up = v > e + 1e-9;
                            e = v;
                            up
                        }
                        None => false,
                    };
                    if extruding && !custom && (nx.is_some() || ny.is_some()) {
                        any = true;
                        // Where the move began is on the print too (the first move of a perimeter).
                        minx = minx.min(sx);
                        maxx = maxx.max(sx);
                        miny = miny.min(sy);
                        maxy = maxy.max(sy);
                        minx = minx.min(x);
                        maxx = maxx.max(x);
                        miny = miny.min(y);
                        maxy = maxy.max(y);
                        maxz = maxz.max(z);
                    }
                }
                _ => {}
            }
        }
    }
    any.then_some(([minx, miny, maxx, maxy], maxz))
}

// ---- binary G-code ------------------------------------------------------------------------------

fn binary(f: &mut File) -> Result<Meta> {
    // Header: "GCDE", version u32, checksum type u16 (0 none, 1 CRC32). Then blocks: type u16,
    // compression u16, uncompressed size u32, [compressed size u32 when compressed], parameters (2
    // bytes, 6 for a thumbnail), data, [CRC32]. Read until the first G-code block.
    let mut head = [0_u8; 6];
    f.read_exact(&mut head).map_err(|e| e.to_string())?;
    let crc = u16::from_le_bytes([head[4], head[5]]) == 1;
    let mut m = Meta {
        binary: true,
        ..Meta::default()
    };
    for _ in 0..16 {
        let mut h = [0_u8; 8];
        if f.read_exact(&mut h).is_err() {
            break;
        }
        let (kind, comp, size) = (
            u16::from_le_bytes([h[0], h[1]]),
            u16::from_le_bytes([h[2], h[3]]),
            u32::from_le_bytes([h[4], h[5], h[6], h[7]]),
        );
        if kind == 1 {
            break; // the G-code: compressed, never read
        }
        let stored = if comp != 0 {
            let mut c = [0_u8; 4];
            f.read_exact(&mut c).map_err(|e| e.to_string())?;
            u32::from_le_bytes(c)
        } else {
            size
        };
        let params = if kind == 5 { 6 } else { 2 };
        f.seek(SeekFrom::Current(params))
            .map_err(|e| e.to_string())?;
        if (kind == 0 || kind == 3 || kind == 4) && comp == 0 && stored <= 1 << 20 {
            let mut data = vec![0_u8; stored as usize];
            f.read_exact(&mut data).map_err(|e| e.to_string())?;
            apply_ini(&mut m, &String::from_utf8_lossy(&data));
        } else {
            f.seek(SeekFrom::Current(i64::from(stored)))
                .map_err(|e| e.to_string())?;
        }
        if crc {
            f.seek(SeekFrom::Current(4)).map_err(|e| e.to_string())?;
        }
    }
    Ok(m)
}

fn apply_ini(m: &mut Meta, text: &str) {
    for line in text.lines() {
        let Some((k, v)) = line.split_once('=') else {
            continue;
        };
        let v = v.trim();
        match k.trim() {
            "Producer" => m.slicer = Some(v.to_owned()),
            "printer_model" if !v.is_empty() => m.printer_model = Some(v.to_owned()),
            "nozzle_diameter" => m.nozzle_mm = v.parse().ok(),
            "filament_type" => {
                m.filament = v
                    .split(';')
                    .map(|x| x.trim().to_owned())
                    .filter(|x| !x.is_empty())
                    .collect()
            }
            "max_layer_z" => m.max_height_mm = v.parse().ok(),
            "objects_info" => {
                if let Ok(j) = serde_json::from_str::<Value>(v) {
                    let (mut minx, mut miny, mut maxx, mut maxy) =
                        (f64::MAX, f64::MAX, f64::MIN, f64::MIN);
                    let mut any = false;
                    for o in j["objects"].as_array().into_iter().flatten() {
                        for p in o["polygon"].as_array().into_iter().flatten() {
                            if let (Some(x), Some(y)) = (p[0].as_f64(), p[1].as_f64()) {
                                minx = minx.min(x);
                                maxx = maxx.max(x);
                                miny = miny.min(y);
                                maxy = maxy.max(y);
                                any = true;
                            }
                        }
                    }
                    if any {
                        m.bounds_mm = Some([minx, miny, maxx, maxy]);
                    }
                }
            }
            _ => {}
        }
    }
    if let (Some(b), Some(z)) = (m.bounds_mm, m.max_height_mm) {
        m.extents_mm = Some([b[2] - b[0], b[3] - b[1], z]);
    }
}

