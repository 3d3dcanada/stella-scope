    /// Finish-2 F06 (2026-10-19): the start G-code's purge line is plastic, but not part of the print; it made a 125 mm bowl read 158 x 213 mm.
    #[test]
    fn the_purge_line_of_the_start_gcode_is_not_part_of_the_size() {
        let file = "; generated by PrusaSlicer 2.9.6\nG90\nM83\n;TYPE:Custom\nG1 X10 Y-3 Z0.3 F3000\nG1 X110 Y-3 E8\nG1 X110 Y-2.5 E0.3\n;LAYER_CHANGE\n;TYPE:External perimeter\nG1 X100 Y100 Z0.2\nG1 X140 Y100 E1\nG1 X140 Y150 E1\nG1 X100 Y150 E1\n;TYPE:Custom\nG1 X200 Y200 E1\n";
        let (b, z) = moves_extent(std::io::Cursor::new(file)).unwrap();
        assert_eq!(b, [100.0, 100.0, 140.0, 150.0], "only the part: the purge line along the front and the end G-code are left out");
        assert_eq!(z, 0.2);
        // A file whose slicer does not say what a stretch of moves is counts every extruding move, as before.
        let plain = "G90\nM83\nG1 X10 Y-3 Z0.3\nG1 X110 Y-3 E8\nG1 X100 Y100 E1\n";
        assert_eq!(moves_extent(std::io::Cursor::new(plain)).unwrap().0, [10.0, -3.0, 110.0, 100.0]);
    }
